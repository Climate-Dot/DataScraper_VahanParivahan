-- Parallel validation tables for the legacy fuel-header reprocess (2026-10-23).
--
-- These are NOT part of the production path. They hold a from-scratch reprocess
-- of history with the corrected fuel mapping, so it can be compared against
-- production before anything is promoted. Promotion itself is an in-place UPDATE
-- of specific columns on the production tables, never a swap with these; see
-- sql/migrations/2026-10-23_legacy_fuel_columns.sql.
--
-- Generated from INFORMATION_SCHEMA against the tables AS THEY ACTUALLY EXIST,
-- so this file cannot drift from reality the way its first version did: that one
-- was written before the ethanol/petrol_ethanol columns were added and then never
-- updated, so it described 49 columns when the live tables had 51.
--
-- Note two deliberate differences from the production tables they mirror:
--   - the RTO pair stores inserted_at as NVARCHAR with no default, because its
--     DDL was generated by a script that coerced every column to NVARCHAR(MAX).
--     Harmless here: both halves of the pair agree, so the positional
--     staging-to-final transfer still works, and the ingestion supplies
--     inserted_at explicitly rather than relying on a default.
--   - the OEM pair keeps inserted_at as DATETIME with (getdate()), matching
--     production.
--
-- Rollback: DROP TABLE each of the four. They can be dropped once the curated
-- layer has been trusted for a full monthly cycle; until then they are the only
-- copy of the reprocessed history.

